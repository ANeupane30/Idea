// Generates components/ui/icons.generated.ts from @material-symbols/svg-400 (Rounded).
// Run `npm run icons` after changing NAMES; the output is committed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = [
  "account_tree", "add", "arrow_back", "arrow_forward", "article", "block", "check", "check_circle",
  "close", "cloud_upload", "contrast", "error", "event_repeat", "flag", "format_list_bulleted", "info",
  "lightbulb", "link", "local_library", "login", "logout", "menu_book", "notes", "open_in_new",
  "picture_as_pdf", "progress_activity", "quiz", "radio_button_unchecked", "school", "schema", "search",
  "signal_cellular_alt", "signal_cellular_alt_1_bar", "signal_cellular_alt_2_bar", "smart_display",
  "swap_horiz", "thumb_down", "thumb_up", "update", "upload_file",
];

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dir = path.join(root, "node_modules", "@material-symbols", "svg-400", "rounded");

function pathData(file) {
  const svg = fs.readFileSync(file, "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`no path in ${file}`);
  return paths.join(" ");
}

const lines = NAMES.map((name) => {
  const outline = pathData(path.join(dir, `${name}.svg`));
  const fillFile = path.join(dir, `${name}-fill.svg`);
  const fill = fs.existsSync(fillFile) ? pathData(fillFile) : outline;
  return `  ${name}: { d: ${JSON.stringify(outline)}, fill: ${JSON.stringify(fill)} },`;
});

const out = `// Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (Rounded, Apache-2.0). Do not edit.
export const ICONS = {
${lines.join("\n")}
} as const;
`;
fs.writeFileSync(path.join(root, "components", "ui", "icons.generated.ts"), out);
console.log(`wrote ${NAMES.length} icons`);
